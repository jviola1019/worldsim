/**
 * Characters and jobs (char.*): small people with a 4-frame walk cycle.
 *
 * Frame order: 1 legs together (body raised 1 px), 2 mid-stride with the
 * near leg lit, 3 legs together, 4 mid-stride with the far leg lit. Figures
 * face RIGHT on a 7 px canvas (8 px when a tool sticks out), body on columns
 * 1..5 like the unit.* sprites in ./units.ts, so the renderer mirrors them
 * for leftward motion and the same anchor rules apply. Clothing, kits and
 * uniforms use team-colour keys T/U/V. Athletic kits are generic and
 * original. See ./select.ts (characterSprite, soldierSprite) for selection.
 */
import { S, type SpriteSheet } from './types';

/** Author a frame as a multi-line block; whitespace is ignored, '.' is transparent. */
const px = (block: string): string[] =>
  block
    .split('\n')
    .map((r) => r.trim())
    .filter((r) => r.length > 0);

