// Round 10: the parameter registry. Reads src/config/balance.ts and writes docs/PARAMETERS.md: every BALANCE
// coefficient with its value, evidence class and meaning, grouped by the file's own sections.
//   node tools/param-registry.mjs            (writes docs/PARAMETERS.md)
//   node tools/param-registry.mjs --stdout   (prints it; tests/config/parameters.test.ts compares)
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('src/config/balance.ts', 'utf8');
const lines = src.split('\n');
const start = lines.findIndex((l) => l.startsWith('export const BALANCE'));
const rows = [];
let section = 'General';
let doc = '';
for (let i = start + 1; i < lines.length; i++) {
  const l = lines[i];
  if (/^};/.test(l)) break;
  const sec = l.match(/^\s*\/\/ -+\s*(.+)$/);
  if (sec) { section = sec[1].trim(); continue; }
  const one = l.match(/^\s*\/\*\*\s*(.*?)\s*\*\/\s*$/);
  if (one) { doc = one[1]; continue; }
  if (/^\s*\/\*\*/.test(l)) { // multi-line doc comment
    const parts = [l.replace(/^\s*\/\*\*\s?/, '')];
    while (!/\*\//.test(lines[i])) { i++; parts.push(lines[i].replace(/^\s*\*\/?\s?/, '').replace(/\*\/\s*$/, '')); }
    doc = parts.join(' ').replace(/\s+/g, ' ').replace(/\*\/\s*$/, '').trim();
    continue;
  }
  const m = l.match(/^  ([A-Za-z_]\w*):\s*(.*)$/);
  if (!m) continue;
  let value = m[2];
  if (value.trim().startsWith('{')) { // object literal (e.g. housing)
    const body = [];
    while (!/^\s*}/.test(lines[++i])) body.push(lines[i].trim().replace(/,$/, ''));
    value = body.join(', ');
  } else value = value.replace(/\s*\/\/.*$/, '').replace(/,\s*$/, '').trim();
  const cls = (doc.match(/\[(E|S|C|T)\]/) ?? [])[1] ?? '?';
  rows.push({ section, key: m[1], value, cls, doc: doc.replace(/\[(E|S|C|T)\]\s*/, '') });
  doc = '';
}

const NAMES = { E: 'evidence-informed shape', S: 'stylized', C: 'calibrated', T: 'technical' };
const count = (c) => rows.filter((r) => r.cls === c).length;
const esc = (t) => String(t).replace(/\|/g, '\\|');
const out = [];
out.push('# Parameter registry');
out.push('');
out.push('Generated by `node tools/param-registry.mjs` from [`src/config/balance.ts`](../src/config/balance.ts); `tests/config/parameters.test.ts` fails if this file is stale or a parameter lacks an evidence class or a description. Do not edit by hand.');
out.push('');
out.push('**Evidence classes**');
out.push('');
out.push('| Class | Meaning | Count |');
out.push('|---|---|---|');
out.push(`| **[E]** evidence-informed shape | The direction or shape follows published evidence (e.g. mortality schedules, demographic transition); magnitudes are rounded and illustrative | ${count('E')} |`);
out.push(`| **[S]** stylized | Chosen for plausible, playable behaviour; not fitted to data | ${count('S')} |`);
out.push(`| **[C]** calibrated | Tuned until a measured simulation outcome met a stated target; the record is named | ${count('C')} |`);
out.push(`| **[T]** technical | An engine or planning setting, not a model assumption | ${count('T')} |`);
out.push('');
out.push(`${rows.length} parameters in \`BALANCE\`. **No coefficient is claimed to be empirically validated against real-world data**; the simulation is a stylized model whose aggregate behaviour is checked by the experiments in [METHODS.md](METHODS.md). The mortality and fertility schedules outside \`BALANCE\` (\`MORTALITY_PRE\`, \`MORTALITY_MODERN\`, \`FERTILITY_SHAPE\`) are [E].`);
let cur = '';
for (const r of rows) {
  if (r.section !== cur) {
    cur = r.section;
    out.push('');
    out.push(`## ${cur.charAt(0).toUpperCase()}${cur.slice(1)}`);
    out.push('');
    out.push('| Parameter | Value | Class | Meaning and evidence |');
    out.push('|---|---|---|---|');
  }
  out.push(`| \`${r.key}\` | \`${esc(r.value)}\` | ${r.cls === '?' ? '?' : `[${r.cls}] ${NAMES[r.cls]}`} | ${esc(r.doc)} |`);
}
out.push('');
const text = out.join('\n');
if (process.argv.includes('--stdout')) process.stdout.write(text);
else { writeFileSync('docs/PARAMETERS.md', text); console.log(`docs/PARAMETERS.md: ${rows.length} parameters (E ${count('E')}, S ${count('S')}, C ${count('C')}, T ${count('T')})`); }
