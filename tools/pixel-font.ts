export const FONT_H = 6;

/** Width in font pixels of a string (1 px gap between glyphs). */
export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text) w += (G[ch] ?? G['*'])[0].length + 1;
  return Math.max(0, w - 1);
}

/** Draw text into an RGBA buffer at (x, y) with an integer scale. */
export function drawText(
  px: Uint8Array,
  W: number,
  H: number,
  text: string,
  x: number,
  y: number,
  scale: number,
  rgb: [number, number, number],
): void {
  let cx = x;
  for (const ch of text) {
    const g = G[ch] ?? G['*'];
    for (let r = 0; r < g.length; r++)
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] !== '#') continue;
        for (let sy = 0; sy < scale; sy++)
          for (let sx = 0; sx < scale; sx++) {
            const X = cx + c * scale + sx;
            const Y = y + r * scale + sy;
            if (X < 0 || Y < 0 || X >= W || Y >= H) continue;
            const i = (Y * W + X) * 4;
            px[i] = rgb[0];
            px[i + 1] = rgb[1];
            px[i + 2] = rgb[2];
            px[i + 3] = 255;
          }
      }
    cx += (g[0].length + 1) * scale;
  }
}
